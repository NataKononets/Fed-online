// 5. Визначення чи є число парним чи непарним: Напишіть програму, яка приймає число і використовуючи if та for, виводить повідомлення про те, чи є число парним чи непарним.
prompt('Введіть число:');
const inputNumber = Number(prompt('Введіть число:'));   
if (Number.isNaN(inputNumber)) {
    console.log('Помилка: введено не число');
} else {
    for (let i = 0; i <= inputNumber; i++) {
        if (i % 2 === 0) {  
            console.log('${i} є парним числом');
        } else {
            console.log('${i} є непарним числом');
        }   
    }
}   

