switch (input) {
    case 'коло':
        console.log('коло 0 сторін');
        break;
    
    case 'квадрат':
        console.log('квадрат 4 сторони');
        break;
    case 'трикутник':
        console.log('трикутник 3 сторони');   
        break;
    case '0':
        console.log('коло');
        break;  
    case '3':
        console.log('трикутник');
        break;  
    case '4':
        console.log('квадрат');
        break;
    default:
        console.log('Any information about ${input}');
        break;}

